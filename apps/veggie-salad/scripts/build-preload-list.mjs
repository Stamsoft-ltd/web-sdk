// Writes src/game/preloadList.ts: every image under static/assets/veggie-salad that the HTML/CSS
// side of the game shows (symbols, board, backgrounds, creatures, HUD, info pages, splash), so
// the loader can fetch AND decode them before the splash appears. Audio has its own loader and
// JSON is not an image; the loader's own art is in here too (the splash shows the same mark).
//
//   node scripts/build-preload-list.mjs   (also runs before `pnpm dev` / `pnpm build`)
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const app = join(dirname(fileURLToPath(import.meta.url)), '..');
const root = join(app, 'static', 'assets', 'veggie-salad');
const SKIP_DIRS = new Set(['audio']);
const IMAGE = /\.(webp|png|svg|jpg)$/;

/** @param {string} dir @returns {string[]} */
const walk = (dir) =>
	readdirSync(dir)
		.sort()
		.flatMap((/** @type {string} */ name) => {
			const path = join(dir, name);
			if (statSync(path).isDirectory()) {
				return SKIP_DIRS.has(relative(root, path)) ? [] : walk(path);
			}
			return IMAGE.test(name) ? [path] : [];
		});

const urls = walk(root).map(
	(/** @type {string} */ path) => `./assets/veggie-salad/${relative(root, path)}`,
);
const out = join(app, 'src', 'game', 'preloadList.ts');
writeFileSync(
	out,
	`// Generated by scripts/build-preload-list.mjs — do not edit. Every image the HTML side of the
// game can show, fetched and decoded by the loader before the splash.
export const PRELOAD_IMAGES: readonly string[] = [
${urls.map((/** @type {string} */ url) => `\t'${url}',`).join('\n')}
];
`,
);
console.log(`${urls.length} images → ${relative(app, out)}`);
